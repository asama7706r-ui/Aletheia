"""Workshop search study (the workshop page, section 10.6), stage 1: witnesses found shape first.

An associative witness generated by the role's names acts on itself by left multiplication. Writing its
basis as the standard words of its ideal (deglex order), each generator g becomes an n x n matrix whose
column for a basis word s is fixed when g*s is itself a basis word, and unknown otherwise (a combination of
smaller basis words). So "all associative witnesses of dimension n" = "all shapes S (subword-closed word
sets of size n) x all values of the unknown columns". The shape is the coarse level; the numbers are solved
for, exactly, with sympy. Shapes run from the smallest dimension up, so a result states the bound reached.

The witness itself is the matrix algebra the generators span; it is checked by the sealed checker
(scorer/certs_v5.py), and its NORM/INV certificate comes from the sealed procedure's
quadratic-algebra method. Nothing here changes a sealed file.
Test 5b copy: the only change from the study's file is that the paths below point to this test's own folders.
Limits of this first version (stated in the result): rational solutions only (a free unknown is set to small
integers); associative witnesses only."""
