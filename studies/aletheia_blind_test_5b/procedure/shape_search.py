# ---------------------------------------------------------------- words and polynomials of the free algebra
def wkey(w, order):
    return (len(w), [order[x] for x in w])


def padd(p, q, s=1):
    out = dict(p)
    for w, c in q.items():
        out[w] = out.get(w, 0) + s * c
        if out[w] == 0:
            del out[w]
    return out


def pmul(p, q):
    out = {}
    for a, x in p.items():
        for b, y in q.items():
            w = a + b
            out[w] = out.get(w, 0) + x * y
            if out[w] == 0:
                del out[w]
    return out


def free_term(ast):
    """A role term in the free associative algebra (bracketings agree there)."""
    t = ast[0]
    if t == "num":
        return {(): Fr(ast[1])} if ast[1] else {}
    if t == "frac":
        return {(): Fr(ast[1], ast[2])}
    if t == "name":
        return {(ast[1],): Fr(1)}
    if t == "neg":
        return {w: -c for w, c in free_term(ast[1]).items()}
    if t == "sum":
        out = {}
        for x in ast[1]:
            out = padd(out, free_term(x))
        return out
    if t == "prod":
        out = {(): Fr(1)}
        for x in ast[1]:
            out = pmul(out, free_term(x))
        return out
    raise ValueError(t)


# ---------------------------------------------------------------- shapes
def shapes(alphabet, n, forbidden_leads, order):
    """Subword-closed sets of n words (with the empty word) containing no forbidden leading word."""
    def subwords_ok(w, S):
        return all(w[i:j] in S for i in range(len(w)) for j in range(i + 1, len(w) + 1) if (i, j) != (0, len(w)))

    def bad(w):
        return any(len(f) <= len(w) and any(w[i:i + len(f)] == f for i in range(len(w) - len(f) + 1))
                   for f in forbidden_leads)

    out = []

    def grow(S, last):
        if len(S) == n:
            out.append(sorted(S, key=lambda w: wkey(w, order)))
            return
        cands = set()
        for s in S:
            for g in alphabet:
                for w in (s + (g,), (g,) + s):
                    if w not in S and subwords_ok(w, S) and not bad(w):
                        cands.add(w)
        for w in sorted(cands, key=lambda w: wkey(w, order)):
            if wkey(w, order) > last:          # each set once: add words in increasing order
                grow(S | {w}, wkey(w, order))
    grow({()}, wkey((), order))
    return out


# ---------------------------------------------------------------- one shape: unknown matrices, exact solve
def matrices_for(S, alphabet, order):
    idx = {w: i for i, w in enumerate(S)}
    n = len(S)
    unknowns = []
    mats = {}
    for g in alphabet:
        M = sp.zeros(n, n)
        for j, s in enumerate(S):
            w = (g,) + s
            if w in idx:
                M[idx[w], j] = 1
            else:
                for i, t in enumerate(S):
                    if wkey(t, order) < wkey(w, order):
                        x = sp.Symbol(f"c_{g}_{j}_{i}")
                        unknowns.append(x)
                        M[i, j] = x
        mats[g] = M
    return mats, unknowns


def eval_matrix(p, mats, n):
    out = sp.zeros(n, n)
    for w, c in p.items():
        M = sp.eye(n)
        for g in w:
            M = M * mats[g]
        out += sp.Rational(c.numerator, c.denominator) * M
    return out


def rational_points(eqs, unknowns, tries=(0, 1, -1, 2)):
    """Rational solutions of the system: solve, then set any free unknown to small integers."""
    eqs = [sp.expand(e) for e in eqs if sp.expand(e) != 0]
    if not eqs:
        sols = [{}]
    else:
        G = sp.groebner(eqs, *unknowns, order="lex")
        if list(G.exprs) == [1]:
            return "none"                      # no solution even over the complex numbers
        sols = sp.solve(list(G.exprs), unknowns, dict=True)
    out = []
    for s in sols:
        free = [x for x in unknowns if x not in s]
        for vals in itertools.product(tries, repeat=min(len(free), 6)) if free else [()]:
            sub = dict(zip(free, vals))
            full = {x: sp.nsimplify(sp.sympify(s.get(x, sub.get(x, 0))).subs(sub)) for x in unknowns}
            if all(v.is_Rational for v in full.values()):
                out.append(full)
                break
    return out


# ---------------------------------------------------------------- the witness: the algebra the matrices span
def fr_mat(M):
    return [[Fr(int(sp.Rational(x).p), int(sp.Rational(x).q)) for x in row] for row in M.tolist()]


def mmul(A, B):
    n = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(n) if A[i][k]) for j in range(n)] for i in range(n)]


class Span:
    """A growing basis of matrices (flattened), with exact coordinates; plain fractions, no sympy."""

    def __init__(self):
        self.rows = []                  # (pivot, residual vector, combination over the basis)
        self.size = 0

    def _reduce(self, v):
        comb = [Fr(0)] * self.size
        v = list(v)
        for p, r, c in self.rows:
            if v[p]:
                f = v[p] / r[p]
                v = [x - f * y for x, y in zip(v, r)]
                for k in range(len(c)):
                    if c[k]:
                        comb[k] += f * c[k]
        return v, comb

    def add(self, v):
        res, comb = self._reduce(v)
        nz = [i for i, x in enumerate(res) if x]
        if not nz:
            return False
        c = [-x for x in comb] + [Fr(1)]
        self.rows = [(p, r, cc + [Fr(0)]) for p, r, cc in self.rows]
        self.rows.append((nz[0], res, c))
        self.size += 1
        return True

    def coords(self, v):
        res, comb = self._reduce(v)
        if any(res):
            return None
        return comb


def witness_from(mats, info, drop, origin, gens):
    names = list(gens) + (["e1"] if origin == "k02" else [])
    F = {g: fr_mat(mats[g]) for g in names}
    n = len(F[names[0]])
    one = [[Fr(int(i == j)) for j in range(n)] for i in range(n)]
    flat = lambda A: [x for row in A for x in row]  # noqa: E731
    span, basis = Span(), []
    span.add(flat(one))
    basis.append(one)
    frontier = [one]
    while frontier and len(basis) <= 16:
        nxt = []
        for M in frontier:
            for g in names:
                N = mmul(M, F[g])
                if span.add(flat(N)):
                    basis.append(N)
                    nxt.append(N)
        frontier = nxt
    d = len(basis)
    if d > 16:
        return None
    table = {}
    for i in range(1, d):
        for j in range(1, d):
            c = span.coords(flat(mmul(basis[i], basis[j])))
            if c is None:
                return None
            for k, x in enumerate(c):
                if x:
                    table[(i, j, k)] = x
    gv = {g: span.coords(flat(F[g])) for g in names}
    tpl = {"n": d, "table": table, "gens": gv}
    w = {"dim": d, "table": [[i, j, k, P.fs(c)] for (i, j, k), c in sorted(table.items())], "theta": None,
         "gens": {g: [P.fs(x) for x in gv[g]] for g in gens}, "q12": None, "q13": None}
    if origin == "k02":
        w["E"] = [P.fs(x) for x in gv["e1"]]
    U = P.UNITS[origin] if "f03" not in info["frames"] else [u for u in P.UNITS[origin] if u not in P.Q5F]
    kept = set(U) - set(drop)
    if d > 1 and ("q12" in kept or "q13" in kept):
        cert = P.quadratic_norm(tpl)
        if cert is None:
            return None
        w["q12" if "q12" in kept else "q13"] = cert
    ok, why = CHK.safe(CHK.check_witness, w, info, sorted(drop))
    return w if ok else None


# ---------------------------------------------------------------- the search
def search(world, drop, nmax=6, deadline=None, log=None, dims=None):
    """Associative witnesses of the candidate `drop`, shape by shape, dimension 1, 2, ..., nmax (or only the
    dimensions in `dims`, when a theorem excludes the others: round 2, Frobenius).
    Returns (witness or None, report): the report states the bound reached and what was skipped."""
    b = world["builds"][0]
    origin, frames = b["origin"], list(b["frames"])
    gens = sorted(b["generators"])
    info = CHK.world_info(world)
    U = [u for u in P.UNITS[origin] if not ("f03" in frames and u in P.Q5F)]
    kept = set(U) - set(drop)
    if "q14" in kept:
        return None, {"skipped": "q14 kept (dimension 1 only, a known kind)"}
    alphabet = (["e1"] if origin == "k02" else []) + gens
    order = {g: i for i, g in enumerate(alphabet)}
    rels, ineqs = [], []
    for op, l, r in P.read_role(b):
        d = padd(free_term(l), free_term(r), -1)
        (rels if op == "=" else ineqs).append(d)
    if origin == "k02":
        rels.append({("e1", "e1"): Fr(1), (): Fr(1)})
    comm_pairs = []
    if "q6" in kept:
        comm_pairs = list(itertools.combinations(alphabet, 2))
    elif origin == "k02" and "q6[on]" in kept:
        comm_pairs = [("e1", g) for g in gens]
    lead_rels = list(rels) + [{(b_, a_): Fr(1), (a_, b_): Fr(-1)} for a_, b_ in comm_pairs]
    forbidden = set()
    for p in lead_rels:
        if p:
            forbidden.add(max(p, key=lambda w: wkey(w, order)))
    import shape_driver as D
    deadline = deadline or (time.time() + 3600)
    rep = {"bound": 0, "partial": None, "shapes": 0, "unresolved": 0}
    if dims:
        rep["dims"] = list(dims)
    for n in (dims or range(1, nmax + 1)):
        if time.time() > deadline:
            rep["stopped"] = "time"
            return None, rep
        items, ctx = [], []
        for S in shapes(alphabet, n, forbidden, order):
            mats, unk = matrices_for(S, alphabet, order)
            eqs = []
            for p in rels:
                eqs += list(eval_matrix(p, mats, n))
            for a_, b_ in comm_pairs:
                eqs += list(mats[a_] * mats[b_] - mats[b_] * mats[a_])
            items.append((len(ctx), eqs, unk))
            ctx.append((S, mats))
        rep["shapes"] += len(items)

        def finish(i, pt, n=n):
            S, mats = ctx[i]
            M = {g: m.subs(pt) for g, m in mats.items()}
            if any(eval_matrix(q, M, n) == sp.zeros(n, n) for q in ineqs):
                return None
            w = witness_from(M, info, drop, origin, gens)
            if w is not None:
                rep["shape"] = [" ".join(s) or "1" for s in S]
            return w
        w, st = D.drive(items, deadline, finish)
        rep["unresolved"] += st["unresolved"]
        if w is not None:
            rep["found_at"] = n
            return w, rep
        if st["unresolved"] and rep["partial"] is None:
            rep["partial"] = n          # from here on, some shape of the dimension was not resolved
        if rep["partial"] is None:
            rep["bound"] = n            # every shape up to n resolved: no witness of these forms up to n
    return None, rep
